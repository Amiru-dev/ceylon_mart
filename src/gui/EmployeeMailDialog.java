    private void jPanel3MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jPanel3MouseClicked
        String to = jTextField1.getText();
        String subject = jTextField2.getText();
        String messageText = jTextArea1.getText();

        if (to.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please specify one recipient", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
        } else if (subject.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter email subject", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
        } else if (messageText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter message", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
        } else if (!to.matches("^(?=.{1,64}@)[A-Za-z0-9\\+_-]+(\\.[A-Za-z0-9\\+_-]+)*@[^-][A-Za-z0-9\\+-]+"
                + "(\\.[A-Za-z0-9\\+-]+)*(\\.[A-Za-z]{2,})$")) {
            JOptionPane.showMessageDialog(this, "Please enter valid email", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
        } else {

            jPanel3.setEnabled(false);
            jLabel4.setEnabled(false);
            jLabel7.setEnabled(false);
            try {
                SendFileEmail.sendEmail(to, subject, messageText, this.email);
                this.dispose();
                JOptionPane.showMessageDialog(null, "Email with attachment sent successfully.", "Success", JOptionPane.PLAIN_MESSAGE, JOptionIcon.SUCCESS.setICon());
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, "Unable to send email.", "Error", JOptionPane.ERROR_MESSAGE, JOptionIcon.ERROR.setICon());
            }
            jPanel3.setEnabled(true);
            jLabel4.setEnabled(true);
            jLabel7.setEnabled(true);
        }
    }//GEN-LAST:event_jPanel3MouseClicked


