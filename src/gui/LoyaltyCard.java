    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String price = jTextField1.getText();

        if (price.isEmpty()) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_CENTER, "Please enter loyality card amount");
        } else {

            if (!price.matches("^(?!0$)([1-9][0-9]*|0\\.[0-9]{0,2}|[1-9][0-9]*\\.[0-9]{0,2})$")) {
                Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_CENTER, "Please enter a valid amount");
                jTextField1.setText("");
                jTextField1.grabFocus();
                return;
            }
            before = 300.00;
            double amount = Double.parseDouble(price);

            if (amount == before) {
                Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_CENTER, "You entered previous loyality card amount");
                jTextField1.setText(String.format("%.2f", amount));
                jTextField1.grabFocus();
            } else {
                LoyaltyCard.setBefore(amount);
                Notifications.getInstance().show(Notifications.Type.SUCCESS, Notifications.Location.BOTTOM_CENTER, "Saved successfully");
                jTextField1.setText(String.format("%.2f", amount));
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

