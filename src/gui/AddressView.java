    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
            String line1 = jTextField1.getText();
            String line2 = jTextField2.getText();
            String city = String.valueOf(jComboBox1.getSelectedItem());

            if (line1.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please fill address line 1", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
            } else if (line2.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please fill address line 2", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
            } else if (city.equals("Select")) {
                JOptionPane.showMessageDialog(this, "Please select a city", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
            } else {

                boolean isFound = false;

                for (int i = 0; i < jTable2.getRowCount(); i++) {
                    String getLine1 = String.valueOf(jTable2.getValueAt(i, 1));
                    String getLine2 = String.valueOf(jTable2.getValueAt(i, 2));
                    String getCity = String.valueOf(jTable2.getValueAt(i, 3));

                    if (getLine1.equals(line1) && getLine2.equals(line2) && getCity.equals(city)) {
                        JOptionPane.showMessageDialog(this, "This address is already added", "Error", JOptionPane.ERROR_MESSAGE, JOptionIcon.ERROR.setICon());
                        isFound = true;
                        break;
                    }
                }

                if (!isFound) {
                    MySQL2.executeIUD("INSERT INTO `employee_address`(`line1`,`line2`,`city_id`,`employee_email`)"
                            + "VALUES('" + line1 + "','" + line2 + "','" + cityMap.get(city) + "','" + this.email + "')");

                    reset();
                    JOptionPane.showMessageDialog(this, "Employee address entered successfully", "Success", JOptionPane.PLAIN_MESSAGE, JOptionIcon.SUCCESS.setICon());
                }
            }

        } catch (Exception e) {
            logger.log(Level.WARNING, "Error", e);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int row = jTable2.getSelectedRow();

        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Please select a row to update", "Information", JOptionPane.INFORMATION_MESSAGE, JOptionIcon.INFO.setICon());
        } else {

            String id = String.valueOf(jTable2.getValueAt(row, 0));

            try {
                String line1 = jTextField1.getText();
                String line2 = jTextField2.getText();
                String city = String.valueOf(jComboBox1.getSelectedItem());

                if (line1.isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Please fill address line 1", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
                } else if (line2.isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Please fill address line 2", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
                } else if (city.equals("Select")) {
                    JOptionPane.showMessageDialog(this, "Please select a city", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());

                } else {
                    ResultSet resultSet = MySQL2.executeSearch("SELECT * FROM `employee_address` WHERE `line1` = '" + line1 + "' AND `line2` = '" + line2 + "'"
                            + " AND `city_id` = '" + cityMap.get(city) + "' AND `employee_email` = '" + this.email + "'");

                    if (resultSet.next()) {
                        JOptionPane.showMessageDialog(this, "No changes detected", "Error", JOptionPane.ERROR_MESSAGE, JOptionIcon.ERROR.setICon());

                    } else {

                        boolean isFound = false;

                        for (int i = 0; i < jTable2.getRowCount(); i++) {
                            String getLine1 = String.valueOf(jTable2.getValueAt(i, 1));
                            String getLine2 = String.valueOf(jTable2.getValueAt(i, 2));
                            String getCity = String.valueOf(jTable2.getValueAt(i, 3));

                            if (getLine1.equals(line1) && getLine2.equals(line2) && getCity.equals(city)) {
                                JOptionPane.showMessageDialog(this, "This address is already added", "Error", JOptionPane.ERROR_MESSAGE, JOptionIcon.ERROR.setICon());
                                isFound = true;
                                break;
                            }
                        }

                        if (!isFound) {
                            MySQL2.executeIUD("UPDATE `employee_address` SET `line1` = '" + line1 + "', `line2` = '" + line2 + "',"
                                    + "`city_id` = '" + cityMap.get(city) + "' WHERE `id` = '" + id + "'");

                            reset();
                            JOptionPane.showMessageDialog(this, "Employee address updated successfully", "Success", JOptionPane.PLAIN_MESSAGE, JOptionIcon.SUCCESS.setICon());
                        }
                    }
                }

            } catch (Exception e) {
                logger.log(Level.WARNING, "Error", e);
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

