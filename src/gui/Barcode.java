    private void code() {
        try {

            Code128Bean code128 = new Code128Bean();
            code128.setHeight(25f);
            code128.setModuleWidth(0.5f);

            code128.setQuietZone(10);
            code128.doQuietZone(true);

            ByteArrayOutputStream baos = new ByteArrayOutputStream();
            BitmapCanvasProvider canvas = new BitmapCanvasProvider(baos, "image/x-png", 400, BufferedImage.TYPE_BYTE_BINARY, false, 0);
            code128.generateBarcode(canvas, jTextField1.getText().trim());
            canvas.finish();

            //write to png file
            FileOutputStream fos = new FileOutputStream("barcode.png");
            fos.write(baos.toByteArray());
            fos.flush();
            fos.close();

            //write to pdf
            Image png = Image.getInstance(baos.toByteArray());
            png.setAbsolutePosition(0, 705);
            png.scalePercent(25);

            Document document;
            document = new Document();

            PdfPTable table = new PdfPTable(1);
            table.getDefaultCell().setBorder(PdfPCell.NO_BORDER);
            for (int aw = 0; aw < Integer.valueOf(jTextField3.getText().trim()); aw++) {
                Paragraph p = new Paragraph();

                p.add(new Chunk(jTextField2.getText().trim(), new Font(Font.FontFamily.TIMES_ROMAN, 25f, Font.BOLD)));
                p.add(new Chunk("\n\n Price : LKR " + jTextField4.getText().trim() + "", new Font(Font.FontFamily.TIMES_ROMAN, 25f, Font.BOLD)));
                PdfPTable intable = new PdfPTable(1);
                intable.getDefaultCell().setBorder(PdfPCell.CHUNK);

                intable.addCell(p);
                intable.addCell(png);
                intable.getDefaultCell().setBorder(0);

                table.addCell(intable);
            }
            
            Paragraph p = new Paragraph(jTextField2.getText());
            p.add("\nPrice Rs: " + jTextField4.getText().trim() + "");
            p.add(png);
            PdfWriter writer = PdfWriter.getInstance(document, new FileOutputStream("C:\\Users\\ASUS™\\Desktop\\Barcode\\barcodes.pdf"));

            document.open();
            document.add(table);

            document.close();

            writer.close();

            this.dispose();
            JOptionPane.showMessageDialog(null, "Barcode generated successfully.", "Success", JOptionPane.PLAIN_MESSAGE, JOptionIcon.SUCCESS.setICon());

        } catch (DocumentException | HeadlessException | IOException | NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Unable to generate barcode", "Error", JOptionPane.ERROR_MESSAGE, JOptionIcon.ERROR.setICon());
        }
    }
