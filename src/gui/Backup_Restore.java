    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        jButton2.setEnabled(false);
        String backupPath = jTextField1.getText().trim();
        
        if (backupPath.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please set a valid backup path", "Information", JOptionPane.INFORMATION_MESSAGE, JOptionIcon.INFO.setICon());
            return;
        }
        
        File backupDir = new File(backupPath);
        if (!backupDir.exists() || !backupDir.isDirectory()) {
            JOptionPane.showMessageDialog(this, "The specified backup path does not exist or is not a directory", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
            return;
        }
        
        if (!backupDir.canWrite()) {
            JOptionPane.showMessageDialog(this, "The application does not have write permissions for the specified backup path", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
            return;
        }
        
        try {
            Date date = new Date();
            String dateStr = new SimpleDateFormat("yyyy-MM-dd").format(date);
            String fileName = jCheckBox1.isSelected() ? "backup_with_db_creation_" : "backup_";
            String path = backupPath + "/" + fileName + dateStr + ".sql";

            // Read database information
            FileInputStream fileInputStream = new FileInputStream("dbinfor.ser");
            MySQL2 db;
            try ( ObjectInputStream objectInputStream = new ObjectInputStream(fileInputStream)) {
                db = (MySQL2) objectInputStream.readObject();
            }
            
            String command;
            if (jCheckBox1.isSelected()) {
                // Include CREATE DATABASE
                command = db.getDump() + " -u" + db.getUsername() + " -p" + db.getPassword()
                        + " --add-drop-database --databases " + db.getDbName() + " -r " + path;
            } else {
                // Exclude CREATE DATABASE
                command = db.getDump() + " -u" + db.getUsername() + " -p" + db.getPassword()
                        + " " + db.getDbName() + " -r " + path;
            }

            // Execute the backup process
            Runtime runtime = Runtime.getRuntime();
            Process p1 = runtime.exec(command);
            int processComplete = p1.waitFor();
            
            if (processComplete == 0) {
                reset();
                JOptionPane.showMessageDialog(this, "Backup completed successfully", "Success",
                        JOptionPane.PLAIN_MESSAGE, JOptionIcon.SUCCESS.setICon());
            } else {
                JOptionPane.showMessageDialog(this, "Backup failed. Please check your MySQL configuration.",
                        "Error", JOptionPane.ERROR_MESSAGE, JOptionIcon.ERROR.setICon());
            }
        } catch (HeadlessException | IOException | ClassNotFoundException | InterruptedException e) {
            JOptionPane.showMessageDialog(this, "An error occurred during the backup process.", "Error",
                    JOptionPane.ERROR_MESSAGE, JOptionIcon.ERROR.setICon());
        }
        jButton2.setEnabled(true);
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        jButton3.setEnabled(false);
        try {
            String restorePath = jTextField1.getText().trim();
            
            if (restorePath.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please set a valid restore path", "Information", JOptionPane.INFORMATION_MESSAGE, JOptionIcon.INFO.setICon());
                return;
            }
            
            File selectedFile = new File(restorePath);
            
            if (!selectedFile.exists() || !selectedFile.isFile() || !selectedFile.getName().toLowerCase().endsWith(".sql")) {
                JOptionPane.showMessageDialog(this, "Please select a valid .sql file", "Warning", JOptionPane.WARNING_MESSAGE, JOptionIcon.WARNING.setICon());
                return;
            }
            
            if (!selectedFile.canRead()) {
                JOptionPane.showMessageDialog(this, "The application does not have read permissions for the selected .sql file", "Error", JOptionPane.ERROR_MESSAGE, JOptionIcon.ERROR.setICon());
                return;
            }
            
            FileInputStream fileInputStream = new FileInputStream("dbinfor.ser");
            MySQL2 db;
            try ( ObjectInputStream objectInputStream = new ObjectInputStream(fileInputStream)) {
                db = (MySQL2) objectInputStream.readObject();
            }
            
            String mysqlPath = "C:\\Program Files\\MySQL\\MySQL Server 8.0\\bin\\mysql";
            ProcessBuilder processBuilder;
            
            if (!restorePath.contains("db_creation")) {
                processBuilder = new ProcessBuilder(
                        mysqlPath,
                        "-u" + db.getUsername(),
                        "-p" + db.getPassword(),
                        db.getDbName()
                );
            } else {
                processBuilder = new ProcessBuilder(
                        mysqlPath,
                        "-u" + db.getUsername(),
                        "-p" + db.getPassword()
                );
            }
            
            processBuilder.redirectInput(selectedFile);
            processBuilder.redirectErrorStream(true);
            
            Process process = processBuilder.start();
            
            int processComplete = process.waitFor();
            
            if (processComplete == 0) {
                reset();
                JOptionPane.showMessageDialog(this, "Restore completed successfully", "Success", JOptionPane.PLAIN_MESSAGE, JOptionIcon.SUCCESS.setICon());
            } else {
                JOptionPane.showMessageDialog(this, "Restore failed. Please check your MySQL configuration.", "Error", JOptionPane.ERROR_MESSAGE, JOptionIcon.ERROR.setICon());
            }
        } catch (HeadlessException | IOException | ClassNotFoundException | InterruptedException e) {
            JOptionPane.showMessageDialog(this, "An error occurred during the restore process", "Error", JOptionPane.ERROR_MESSAGE, JOptionIcon.ERROR.setICon());
        }
        jButton3.setEnabled(true);
    }//GEN-LAST:event_jButton3ActionPerformed

